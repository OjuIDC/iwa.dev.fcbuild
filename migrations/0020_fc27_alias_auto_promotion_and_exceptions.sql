CREATE OR REPLACE FUNCTION public.fc27_record_manual_alias_promotion_audit(
    p_candidate_id bigint,
    p_player_id text,
    p_promotion_mode text,
    p_policy_version text,
    p_minimum_distinct_matches integer,
    p_distinct_match_count integer,
    p_prior_verification_status text,
    p_prior_conflict_status text,
    p_resulting_roster_revision text,
    p_refresh_job_id bigint,
    p_promoted_at timestamptz DEFAULT pg_catalog.clock_timestamp()
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
    v_player_id text;
    v_mode text;
    v_policy_version text;
    v_revision text;
    v_prior_ver text;
    v_prior_conf text;
    v_promoted_at timestamptz;
    v_created_at timestamptz;
    v_audit_id bigint;
BEGIN
    IF p_player_id IS NULL THEN
        RAISE EXCEPTION 'player_id is required' USING ERRCODE = '22023';
    END IF;
    v_player_id := pg_catalog.btrim(p_player_id);
    IF pg_catalog.char_length(v_player_id) < 1
       OR pg_catalog.char_length(v_player_id) > 64
       OR v_player_id ~ '[\x00-\x20\x7F:]' THEN
        RAISE EXCEPTION 'invalid player_id for manual promotion audit' USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.fc27_roster AS r WHERE r.player_id = v_player_id
    ) THEN
        RAISE EXCEPTION 'unknown roster player_id for manual promotion audit' USING ERRCODE = '23503';
    END IF;

    v_mode := pg_catalog.upper(pg_catalog.btrim(COALESCE(p_promotion_mode, '')));
    IF v_mode NOT IN ('MANUAL_OPERATOR_CONFIRMATION', 'MANUAL_CORRECTION') THEN
        RAISE EXCEPTION 'manual promotion audit mode must be MANUAL_OPERATOR_CONFIRMATION or MANUAL_CORRECTION'
            USING ERRCODE = '22023';
    END IF;

    v_policy_version := pg_catalog.btrim(COALESCE(p_policy_version, 'manual-v1'));
    IF v_policy_version !~ '^[A-Za-z0-9][A-Za-z0-9_.-]{0,31}$' THEN
        RAISE EXCEPTION 'invalid policy_version' USING ERRCODE = '22023';
    END IF;

    v_revision := pg_catalog.btrim(COALESCE(p_resulting_roster_revision, ''));
    IF v_revision !~ '^[A-Za-z0-9][A-Za-z0-9_.-]{0,31}$' THEN
        RAISE EXCEPTION 'invalid resulting_roster_revision' USING ERRCODE = '22023';
    END IF;

    IF p_minimum_distinct_matches IS NULL
       OR p_minimum_distinct_matches < 2
       OR p_minimum_distinct_matches > 10 THEN
        RAISE EXCEPTION 'minimum_distinct_matches must be between 2 and 10' USING ERRCODE = '22023';
    END IF;
    IF p_distinct_match_count IS NULL OR p_distinct_match_count < 1 THEN
        RAISE EXCEPTION 'distinct_match_count must be >= 1' USING ERRCODE = '22023';
    END IF;

    v_prior_ver := pg_catalog.upper(pg_catalog.btrim(COALESCE(p_prior_verification_status, 'NONE')));
    IF v_prior_ver NOT IN ('NONE', 'OBSERVED', 'STABLE', 'CONFLICTED', 'OPERATOR_VERIFIED', 'PROMOTED', 'REJECTED') THEN
        RAISE EXCEPTION 'invalid prior_verification_status' USING ERRCODE = '22023';
    END IF;

    v_prior_conf := pg_catalog.upper(pg_catalog.btrim(COALESCE(p_prior_conflict_status, 'NONE')));
    IF v_prior_conf NOT IN ('NONE', 'CONFLICTED', 'SAME_PLAYER_MULTIPLE_ALIASES', 'CROSS_PLAYER_SAME_ALIAS', 'BOTH') THEN
        RAISE EXCEPTION 'invalid prior_conflict_status' USING ERRCODE = '22023';
    END IF;

    v_promoted_at := COALESCE(p_promoted_at, pg_catalog.clock_timestamp());
    v_created_at := GREATEST(v_promoted_at, pg_catalog.clock_timestamp());

    INSERT INTO public.fc27_player_alias_promotion_audit (
        candidate_id,
        player_id,
        promotion_mode,
        policy_version,
        minimum_distinct_matches,
        distinct_match_count,
        prior_verification_status,
        prior_conflict_status,
        resulting_roster_revision,
        refresh_job_id,
        promoted_at,
        outcome_category,
        created_at
    ) VALUES (
        p_candidate_id,
        v_player_id,
        v_mode,
        v_policy_version,
        p_minimum_distinct_matches,
        p_distinct_match_count,
        v_prior_ver,
        v_prior_conf,
        v_revision,
        p_refresh_job_id,
        v_promoted_at,
        'PROMOTED',
        v_created_at
    )
    ON CONFLICT (player_id, COALESCE(candidate_id, 0), promotion_mode, resulting_roster_revision)
    DO NOTHING
    RETURNING fc27_player_alias_promotion_audit.audit_id INTO v_audit_id;

    IF v_audit_id IS NULL THEN
        SELECT a.audit_id
          INTO v_audit_id
        FROM public.fc27_player_alias_promotion_audit AS a
        WHERE a.player_id = v_player_id
          AND COALESCE(a.candidate_id, 0) = COALESCE(p_candidate_id, 0)
          AND a.promotion_mode = v_mode
          AND a.resulting_roster_revision = v_revision;
    END IF;

    RETURN v_audit_id;
END;
$$;

ALTER FUNCTION public.fc27_record_manual_alias_promotion_audit(
    bigint, text, text, text, integer, integer, text, text, text, bigint, timestamptz
) OWNER TO fc27_owner;

REVOKE ALL ON FUNCTION public.fc27_record_manual_alias_promotion_audit(
    bigint, text, text, text, integer, integer, text, text, text, bigint, timestamptz
) FROM PUBLIC;


CREATE OR REPLACE FUNCTION public.fc27_purge_resolved_alias_review_exceptions(
    p_retention_days integer DEFAULT 90,
    p_now timestamptz DEFAULT pg_catalog.clock_timestamp()
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
    v_deleted integer := 0;
    v_cutoff timestamptz;
BEGIN
    IF p_retention_days IS NULL OR p_retention_days < 1 OR p_retention_days > 3650 THEN
        RAISE EXCEPTION 'retention_days must be between 1 and 3650' USING ERRCODE = '22023';
    END IF;
    v_cutoff := COALESCE(p_now, pg_catalog.clock_timestamp())
        - pg_catalog.make_interval(days => p_retention_days);

    DELETE FROM public.fc27_player_alias_review_exceptions
    WHERE exception_state IN ('RESOLVED', 'REJECTED')
      AND resolved_at IS NOT NULL
      AND resolved_at < v_cutoff;

    GET DIAGNOSTICS v_deleted = ROW_COUNT;
    RETURN v_deleted;
END;
$$;

ALTER FUNCTION public.fc27_purge_resolved_alias_review_exceptions(integer, timestamptz)
    OWNER TO fc27_owner;

REVOKE ALL ON FUNCTION public.fc27_purge_resolved_alias_review_exceptions(integer, timestamptz)
    FROM PUBLIC;
