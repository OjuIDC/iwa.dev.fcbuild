CREATE OR REPLACE FUNCTION public.fc27_evaluate_alias_candidates_for_promotion(
    p_minimum_distinct_matches integer DEFAULT 2,
    p_no_alias_min_appearances integer DEFAULT 3
)
RETURNS TABLE (
    entry_kind text,
    candidate_id bigint,
    player_id text,
    distinct_match_count integer,
    observation_count integer,
    first_seen_at timestamptz,
    reason_category text,
    exception_reason text
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
    v_min_matches integer;
    v_no_alias_min integer;
BEGIN
    IF p_minimum_distinct_matches IS NULL
       OR p_minimum_distinct_matches < 2
       OR p_minimum_distinct_matches > 10 THEN
        RAISE EXCEPTION 'minimum_distinct_matches must be between 2 and 10'
            USING ERRCODE = '22023';
    END IF;
    IF p_no_alias_min_appearances IS NULL
       OR p_no_alias_min_appearances < 1
       OR p_no_alias_min_appearances > 100 THEN
        RAISE EXCEPTION 'no_alias_min_appearances must be between 1 and 100'
            USING ERRCODE = '22023';
    END IF;
    v_min_matches := p_minimum_distinct_matches;
    v_no_alias_min := p_no_alias_min_appearances;

    RETURN QUERY
    WITH active_candidates AS (
        SELECT
            c.candidate_id,
            c.player_id,
            c.public_alias,
            c.public_alias_normalized,
            c.observation_count,
            c.distinct_match_count,
            c.first_seen_at,
            c.verification_status,
            c.conflict_status,
            COUNT(*) OVER (PARTITION BY c.player_id) AS player_active_count,
            COUNT(*) OVER (
                PARTITION BY public.fc27_normalize_alias_comparison_key(c.public_alias_normalized)
            ) AS norm_alias_active_count
        FROM public.fc27_player_alias_candidates AS c
        WHERE c.verification_status <> 'REJECTED'
    ),
    candidate_eval AS (
        SELECT
            'CANDIDATE'::text AS entry_kind,
            c.candidate_id,
            c.player_id,
            c.distinct_match_count,
            c.observation_count,
            c.first_seen_at,
            CASE
                WHEN c.verification_status = 'REJECTED' THEN 'REJECTED'
                WHEN c.verification_status = 'PROMOTED' THEN 'ALREADY_PROMOTED'
                WHEN NOT (
                    pg_catalog.char_length(pg_catalog.btrim(c.public_alias)) BETWEEN 1 AND 32
                    AND c.public_alias = pg_catalog.btrim(c.public_alias)
                    AND c.public_alias !~ '[\x00-\x1F\x7F]'
                    AND pg_catalog.left(c.public_alias, 1) NOT IN ('=', '+', '-', '@')
                    AND c.public_alias !~* '(plr_ecf_[0-9a-f]{12}|mref_ecf_[0-9a-f]{12,64}|https?://|www\.|@(everyone|here)|<@[!&]?[0-9]+>|<#[0-9]+>|postgresql://|postgres://|redis://|bearer\s+|password|secret|^\s*unnamed\s+player\s*$)'
                ) THEN 'INVALID_ALIAS'
                WHEN COALESCE(ac.player_active_count, 0) > 1
                     OR c.conflict_status = 'SAME_PLAYER_MULTIPLE_ALIASES' THEN 'MULTIPLE_ACTIVE_ALIASES'
                WHEN COALESCE(ac.norm_alias_active_count, 0) > 1
                     OR c.conflict_status = 'CROSS_PLAYER_SAME_ALIAS' THEN 'CROSS_PLAYER_ALIAS_COLLISION'
                WHEN c.conflict_status <> 'NONE' OR c.verification_status = 'CONFLICTED' THEN 'CONFLICTED'
                WHEN c.verification_status = 'OBSERVED' THEN 'OBSERVED_ONLY'
                WHEN c.verification_status <> 'STABLE' THEN 'STALE_RECHECK'
                WHEN c.distinct_match_count < v_min_matches THEN 'BELOW_MATCH_THRESHOLD'
                WHEN EXISTS (
                    SELECT 1
                    FROM public.fc27_roster AS r
                    WHERE r.player_id = c.player_id
                       OR (
                           r.active = TRUE
                           AND r.display_name_comparison_key IN (
                               public.fc27_normalize_alias_comparison_key(c.public_alias_normalized),
                               public.fc27_normalize_alias_comparison_key(c.public_alias)
                           )
                       )
                ) THEN 'ROSTER_ALREADY_EXISTS'
                ELSE 'ELIGIBLE'
            END AS reason_category,
            CASE
                WHEN c.verification_status IN ('PROMOTED', 'REJECTED') THEN NULL::text
                WHEN NOT (
                    pg_catalog.char_length(pg_catalog.btrim(c.public_alias)) BETWEEN 1 AND 32
                    AND c.public_alias = pg_catalog.btrim(c.public_alias)
                    AND c.public_alias !~ '[\x00-\x1F\x7F]'
                    AND pg_catalog.left(c.public_alias, 1) NOT IN ('=', '+', '-', '@')
                    AND c.public_alias !~* '(plr_ecf_[0-9a-f]{12}|mref_ecf_[0-9a-f]{12,64}|https?://|www\.|@(everyone|here)|<@[!&]?[0-9]+>|<#[0-9]+>|postgresql://|postgres://|redis://|bearer\s+|password|secret|^\s*unnamed\s+player\s*$)'
                ) THEN 'INVALID_ALIAS'
                WHEN EXISTS (
                    SELECT 1
                    FROM public.fc27_roster AS r
                    WHERE r.player_id = c.player_id
                      AND r.active = TRUE
                      AND r.display_name_comparison_key NOT IN (
                          public.fc27_normalize_alias_comparison_key(c.public_alias_normalized),
                          public.fc27_normalize_alias_comparison_key(c.public_alias)
                      )
                ) AND EXISTS (
                    SELECT 1
                    FROM public.fc27_player_alias_candidates AS cp
                    WHERE cp.player_id = c.player_id
                      AND cp.candidate_id <> c.candidate_id
                      AND cp.verification_status = 'PROMOTED'
                ) THEN 'PROVIDER_ALIAS_CHANGED'
                WHEN c.conflict_status IN ('CROSS_PLAYER_SAME_ALIAS', 'BOTH')
                     OR COALESCE(ac.norm_alias_active_count, 0) > 1 THEN 'CROSS_PLAYER_SAME_ALIAS'
                WHEN c.conflict_status IN ('SAME_PLAYER_MULTIPLE_ALIASES', 'CONFLICTED')
                     OR COALESCE(ac.player_active_count, 0) > 1 THEN 'SAME_PLAYER_MULTIPLE_ALIASES'
                WHEN EXISTS (
                    SELECT 1
                    FROM public.fc27_roster AS r
                    WHERE r.player_id = c.player_id
                       OR (
                           r.active = TRUE
                           AND r.display_name_comparison_key IN (
                               public.fc27_normalize_alias_comparison_key(c.public_alias_normalized),
                               public.fc27_normalize_alias_comparison_key(c.public_alias)
                           )
                       )
                ) THEN 'EXISTING_ROSTER_CONFLICT'
                WHEN c.verification_status = 'STABLE'
                     AND c.distinct_match_count < v_min_matches
                     AND c.observation_count >= v_no_alias_min THEN 'MANUAL_REVIEW_REQUIRED'
                WHEN c.verification_status = 'OBSERVED'
                     AND c.observation_count >= v_no_alias_min THEN 'MANUAL_REVIEW_REQUIRED'
                ELSE NULL::text
            END AS exception_reason
        FROM public.fc27_player_alias_candidates AS c
        LEFT JOIN active_candidates AS ac
            ON ac.candidate_id = c.candidate_id
    ),
    missing_alias_players AS (
        SELECT
            'UNRESOLVED_PLAYER'::text AS entry_kind,
            NULL::bigint AS candidate_id,
            pms.local_player_reference AS player_id,
            pg_catalog.count(DISTINCT pms.match_id)::integer AS distinct_match_count,
            pg_catalog.count(*)::integer AS observation_count,
            pg_catalog.min(m.played_at) AS first_seen_at,
            'STALE_RECHECK'::text AS reason_category,
            'NO_PROVIDER_ALIAS'::text AS exception_reason
        FROM public.fc27_player_match_stats AS pms
        INNER JOIN public.fc27_matches AS m
            ON m.match_id = pms.match_id
        LEFT JOIN public.fc27_roster AS r
            ON r.player_id = pms.local_player_reference
           AND r.active = TRUE
        WHERE pms.local_player_reference IS NOT NULL
          AND pg_catalog.btrim(pms.local_player_reference) <> ''
          AND r.player_id IS NULL
          AND NOT EXISTS (
              SELECT 1
              FROM public.fc27_player_alias_candidates AS c2
              WHERE c2.player_id = pms.local_player_reference
                AND c2.verification_status <> 'REJECTED'
          )
        GROUP BY pms.local_player_reference
        HAVING pg_catalog.count(DISTINCT pms.match_id) >= v_no_alias_min
    )
    SELECT
        ce.entry_kind,
        ce.candidate_id,
        ce.player_id,
        ce.distinct_match_count,
        ce.observation_count,
        ce.first_seen_at,
        ce.reason_category,
        ce.exception_reason
    FROM candidate_eval AS ce
    UNION ALL
    SELECT
        ma.entry_kind,
        ma.candidate_id,
        ma.player_id,
        ma.distinct_match_count,
        ma.observation_count,
        ma.first_seen_at,
        ma.reason_category,
        ma.exception_reason
    FROM missing_alias_players AS ma
    ORDER BY 1 ASC, 4 DESC, 5 DESC, 6 ASC, 2 ASC NULLS LAST, 3 ASC;
END;
$$;

