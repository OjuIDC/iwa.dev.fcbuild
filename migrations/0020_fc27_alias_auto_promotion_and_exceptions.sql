-- Migration 0020: Stable Provider-Alias Auto-Promotion, Promotion Audit & Review Exceptions
-- Additive, idempotent migration. Never modifies Migrations 0001-0019.
--
-- 1. Adds append-only `public.fc27_player_alias_promotion_audit` to durably record
--    auto-promotions and manual promotions/corrections without storing raw provider
--    payloads, Discord IDs, raw HMACs, or secrets.
-- 2. Adds `public.fc27_player_alias_review_exceptions` to persist conflict, collision,
--    invalid-alias, changed-alias, and repeated-unmapped identity review workloads without
--    duplicate open rows.
-- 3. Adds owner-controlled `SECURITY DEFINER` function
--    `public.fc27_auto_promote_stable_alias_candidate(bigint, text, integer, boolean)` so
--    `fc27_poll_writer` can promote strictly unambiguous `STABLE` candidates atomically
--    without direct table privileges on `public.fc27_roster` or queue mutation access
--    on `public.fc27_discord_jobs`.
-- 4. Adds read-only owner-controlled `SECURITY DEFINER` evaluation function
--    `public.fc27_evaluate_alias_candidates_for_promotion(integer, integer)` for
--    fail-closed shadow-mode, active-mode, and exception-queue classification without
--    exposing `public.fc27_roster` directly to `fc27_poll_writer`.

