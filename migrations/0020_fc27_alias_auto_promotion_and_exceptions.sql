    v_seed_player_id text;
    v_seed_norm_alias text;
    v_seed_comp_key text;
    v_cand record;
    v_player_active_count integer;
    v_alias_active_count integer;
    v_roster_conflict_count integer;
    v_existing_roster_updated_at timestamptz;
    v_existing_revision text;
    v_roster_display_name text;
    v_roster_norm_name text;
    v_roster_comp_key text;
    v_alias_comp_key text;
    v_now timestamptz;
    v_promoted_at timestamptz;
    v_epoch_us bigint;
    v_roster_revision text;
    v_refresh_job_id bigint;
    v_audit_id bigint;
BEGIN
    IF p_candidate_id IS NULL OR p_candidate_id < 1 THEN
        RAISE EXCEPTION 'candidate_id must be a positive integer' USING ERRCODE = '22023';
    END IF;
    IF p_policy_version IS NULL THEN
        RAISE EXCEPTION 'policy_version is required' USING ERRCODE = '22023';
    END IF;
    v_policy_version := pg_catalog.btrim(p_policy_version);
    IF v_policy_version !~ '^[A-Za-z0-9][A-Za-z0-9_.-]{0,31}$' THEN
        RAISE EXCEPTION 'policy_version must match ^[A-Za-z0-9][A-Za-z0-9_.-]{0,31}$'
            USING ERRCODE = '22023';
    END IF;
    IF p_minimum_distinct_matches IS NULL
       OR p_minimum_distinct_matches < 2
       OR p_minimum_distinct_matches > 10 THEN
        RAISE EXCEPTION 'minimum_distinct_matches must be between 2 and 10'
            USING ERRCODE = '22023';
    END IF;

    SELECT c.player_id, c.public_alias_normalized
      INTO v_seed_player_id, v_seed_norm_alias
    FROM public.fc27_player_alias_candidates AS c
    WHERE c.candidate_id = p_candidate_id;

    IF NOT FOUND THEN
        RETURN QUERY SELECT
            FALSE,
            'STALE_RECHECK'::text,
            NULL::text,
            NULL::text,
            NULL::bigint,
            NULL::bigint;
        RETURN;
    END IF;

    v_seed_comp_key := public.fc27_normalize_alias_comparison_key(v_seed_norm_alias);

    -- Lock all non-REJECTED candidates touching this player or canonical comparison key in
    -- ascending candidate_id order to guarantee deadlock-free concurrent serialization.
    PERFORM c.candidate_id
    FROM public.fc27_player_alias_candidates AS c
    WHERE c.candidate_id = p_candidate_id
       OR (
           c.verification_status <> 'REJECTED'
           AND (
               c.player_id = v_seed_player_id
               OR public.fc27_normalize_alias_comparison_key(c.public_alias_normalized) = v_seed_comp_key
           )
       )
    ORDER BY c.candidate_id ASC
    FOR UPDATE;

    SELECT
        c.candidate_id,
        c.player_id,
        c.public_alias,
        c.public_alias_normalized,
        c.distinct_match_count,
        c.verification_status,
        c.conflict_status,
        c.first_seen_at
      INTO v_cand
    FROM public.fc27_player_alias_candidates AS c
    WHERE c.candidate_id = p_candidate_id
    FOR UPDATE;

    IF NOT FOUND THEN
        RETURN QUERY SELECT
            FALSE,
            'STALE_RECHECK'::text,
            NULL::text,
            NULL::text,
            NULL::bigint,
            NULL::bigint;
        RETURN;
    END IF;

    IF v_cand.verification_status = 'PROMOTED' THEN
        SELECT r.updated_at
          INTO v_existing_roster_updated_at
        FROM public.fc27_roster AS r
        WHERE r.player_id = v_cand.player_id;

        IF v_existing_roster_updated_at IS NOT NULL THEN
            v_epoch_us := GREATEST(
                0::bigint,
                pg_catalog.trunc(
                    pg_catalog.date_part('epoch', v_existing_roster_updated_at) * 1000000
                )::bigint
            );
            v_existing_revision := 'u' || pg_catalog.lpad(pg_catalog.to_hex(v_epoch_us), 14, '0');
        ELSE
            v_existing_revision := NULL;
        END IF;

        RETURN QUERY SELECT
            FALSE,
            'ALREADY_PROMOTED'::text,
            v_cand.player_id,
            v_existing_revision,
            NULL::bigint,
            NULL::bigint;
        RETURN;
    END IF;

    IF v_cand.verification_status = 'REJECTED' THEN
        RETURN QUERY SELECT
            FALSE,
            'REJECTED'::text,
            v_cand.player_id,
            NULL::text,
            NULL::bigint,
            NULL::bigint;
        RETURN;
    END IF;

    v_roster_display_name := pg_catalog.btrim(v_cand.public_alias);
    v_roster_norm_name := pg_catalog.lower(v_roster_display_name);
    v_roster_comp_key := public.fc27_normalize_alias_comparison_key(v_cand.public_alias_normalized);
    v_alias_comp_key := public.fc27_normalize_alias_comparison_key(v_cand.public_alias);

    IF NOT (
        pg_catalog.char_length(v_roster_display_name) BETWEEN 1 AND 32
        AND v_cand.public_alias = v_roster_display_name
        AND v_cand.public_alias !~ '[\x00-\x1F\x7F]'
        AND pg_catalog.left(v_roster_display_name, 1) NOT IN ('=', '+', '-', '@')
        AND v_cand.public_alias !~* '(plr_ecf_[0-9a-f]{12}|mref_ecf_[0-9a-f]{12,64}|https?://|www\.|@(everyone|here)|<@[!&]?[0-9]+>|<#[0-9]+>|postgresql://|postgres://|redis://|bearer\s+|password|secret|^\s*unnamed\s+player\s*$)'
    ) THEN
        RETURN QUERY SELECT
            FALSE,
            'INVALID_ALIAS'::text,
            v_cand.player_id,
            NULL::text,
            NULL::bigint,
            NULL::bigint;
        RETURN;
    END IF;

    SELECT pg_catalog.count(*)::integer
      INTO v_player_active_count
    FROM public.fc27_player_alias_candidates AS c
    WHERE c.player_id = v_cand.player_id
      AND c.verification_status <> 'REJECTED';

    IF v_player_active_count > 1 THEN
        RETURN QUERY SELECT
            FALSE,
            'MULTIPLE_ACTIVE_ALIASES'::text,
            v_cand.player_id,
            NULL::text,
            NULL::bigint,
            NULL::bigint;
        RETURN;
    END IF;

    SELECT pg_catalog.count(DISTINCT c.player_id)::integer
      INTO v_alias_active_count
    FROM public.fc27_player_alias_candidates AS c
    WHERE c.verification_status <> 'REJECTED'
      AND public.fc27_normalize_alias_comparison_key(c.public_alias_normalized) IN (
          v_roster_comp_key,
          v_alias_comp_key
      );

    IF v_alias_active_count > 1 THEN
        RETURN QUERY SELECT
            FALSE,
            'CROSS_PLAYER_ALIAS_COLLISION'::text,
            v_cand.player_id,
            NULL::text,
            NULL::bigint,
            NULL::bigint;
        RETURN;
    END IF;

    IF v_cand.conflict_status <> 'NONE' OR v_cand.verification_status = 'CONFLICTED' THEN
        RETURN QUERY SELECT
            FALSE,
            'CONFLICTED'::text,
            v_cand.player_id,
            NULL::text,
            NULL::bigint,
            NULL::bigint;
        RETURN;
    END IF;

    IF v_cand.verification_status = 'OBSERVED' THEN
        RETURN QUERY SELECT
            FALSE,
            'OBSERVED_ONLY'::text,
            v_cand.player_id,
            NULL::text,
            NULL::bigint,
            NULL::bigint;
        RETURN;
    END IF;

    IF v_cand.verification_status <> 'STABLE' THEN
        RETURN QUERY SELECT
            FALSE,
            'STALE_RECHECK'::text,
            v_cand.player_id,
            NULL::text,
            NULL::bigint,
            NULL::bigint;
        RETURN;
    END IF;

    IF v_cand.distinct_match_count < p_minimum_distinct_matches THEN
        RETURN QUERY SELECT
            FALSE,
            'BELOW_MATCH_THRESHOLD'::text,
            v_cand.player_id,
            NULL::text,
            NULL::bigint,
            NULL::bigint;
        RETURN;
    END IF;

    -- Lock any matching canonical roster rows deterministically; never overwrite or rename.
    PERFORM r.player_id
    FROM public.fc27_roster AS r
    WHERE r.player_id = v_cand.player_id
       OR (
           r.active = TRUE
           AND r.display_name_comparison_key IN (v_roster_comp_key, v_alias_comp_key)
       )
    ORDER BY r.player_id ASC
    FOR UPDATE;

    SELECT pg_catalog.count(*)::integer
      INTO v_roster_conflict_count
    FROM public.fc27_roster AS r
    WHERE r.player_id = v_cand.player_id
       OR (
           r.active = TRUE
           AND r.display_name_comparison_key IN (v_roster_comp_key, v_alias_comp_key)
       );

    IF v_roster_conflict_count > 0 THEN
        RETURN QUERY SELECT
            FALSE,
            'ROSTER_ALREADY_EXISTS'::text,
            v_cand.player_id,
            NULL::text,
            NULL::bigint,
            NULL::bigint;
        RETURN;
    END IF;

    v_now := pg_catalog.clock_timestamp();
    v_promoted_at := GREATEST(v_now, v_cand.first_seen_at);

    INSERT INTO public.fc27_roster (
        player_id,
        display_name,
        display_name_normalized,
        display_name_comparison_key,
        position,
        discord_user_id,
        active,
        created_at,
        updated_at
    ) VALUES (
        v_cand.player_id,
        v_roster_display_name,
        v_roster_norm_name,
        v_alias_comp_key,
        NULL,
        NULL,
        TRUE,
        v_promoted_at,
        v_promoted_at
    );

    UPDATE public.fc27_manual_match_players AS mmp
    SET safe_display_label = v_roster_display_name,
        normalized_display_label = v_roster_norm_name,
        updated_at = v_promoted_at
    WHERE mmp.player_id = v_cand.player_id;

    UPDATE public.fc27_player_alias_candidates AS c
    SET verification_status = 'PROMOTED',
        promoted_at = v_promoted_at,
        updated_at = GREATEST(v_promoted_at, c.updated_at)
    WHERE c.candidate_id = p_candidate_id;

    v_epoch_us := GREATEST(
        0::bigint,
        pg_catalog.trunc(
            pg_catalog.date_part('epoch', v_promoted_at) * 1000000
        )::bigint
    );
    v_roster_revision := 'u' || pg_catalog.lpad(pg_catalog.to_hex(v_epoch_us), 14, '0');

    IF COALESCE(p_enqueue_refresh, TRUE) THEN
        v_refresh_job_id := public.fc27_enqueue_roster_refresh_job(
            v_cand.player_id,
            v_roster_revision,
            'ROSTER_UPSERT',
            v_promoted_at
        );
    ELSE
        v_refresh_job_id := NULL;
    END IF;

    INSERT INTO public.fc27_player_alias_promotion_audit (
        candidate_id,
        player_id,
        promotion_mode,
        policy_version,
        minimum_distinct_matches,
        distinct_match_count,
        prior_verification_status,
        prior_conflict_status,
        resulting_roster_revision,
        refresh_job_id,
        promoted_at,
        outcome_category,
        created_at
    ) VALUES (
        p_candidate_id,
        v_cand.player_id,
        'AUTO_STABLE_PROVIDER_ALIAS',
        v_policy_version,
        p_minimum_distinct_matches,
        v_cand.distinct_match_count,
        v_cand.verification_status,
        v_cand.conflict_status,
        v_roster_revision,
        v_refresh_job_id,
        v_promoted_at,
        'PROMOTED',
        v_promoted_at
    )
    RETURNING fc27_player_alias_promotion_audit.audit_id INTO v_audit_id;

    UPDATE public.fc27_player_alias_review_exceptions AS e
    SET exception_state = 'RESOLVED',
        resolved_at = v_promoted_at,
        resolved_observation_count = COALESCE(src.cand_obs, e.observation_count),
        resolved_distinct_match_count = COALESCE(src.cand_distinct, e.distinct_match_count),
        resolved_last_seen_at = COALESCE(src.cand_last_seen, e.last_detected_at),
        resolved_candidate_state_digest = src.state_digest,
        updated_at = GREATEST(v_promoted_at, e.updated_at)
    FROM (
        SELECT
            e2.exception_id,
            c.observation_count AS cand_obs,
            c.distinct_match_count AS cand_distinct,
            c.last_seen_at AS cand_last_seen,
            CASE
                WHEN c.candidate_id IS NOT NULL THEN
                    pg_catalog.encode(
                        pg_catalog.sha256(
                            pg_catalog.convert_to(
                                'cand:' || c.candidate_id::text || ':' || c.verification_status || ':' || c.conflict_status,
                                'UTF8'
                            )
                        ),
                        'hex'
                    )
                ELSE
                    pg_catalog.encode(
                        pg_catalog.sha256(
                            pg_catalog.convert_to('no_cand:' || e2.exception_reason, 'UTF8')
                        ),
                        'hex'
                    )
            END AS state_digest
        FROM public.fc27_player_alias_review_exceptions AS e2
        LEFT JOIN public.fc27_player_alias_candidates AS c
            ON c.candidate_id = e2.candidate_id
        WHERE e2.player_id = v_cand.player_id
          AND e2.exception_state IN ('OPEN', 'ACKNOWLEDGED', 'DEFERRED')
    ) AS src
    WHERE e.exception_id = src.exception_id;

    RETURN QUERY SELECT
        TRUE,
        'PROMOTED'::text,
        v_cand.player_id,
        v_roster_revision,
        v_refresh_job_id,
        v_audit_id;
END;
$$;

