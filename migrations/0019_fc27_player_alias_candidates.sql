-- Migration 0019: Protected Provider Alias Candidates & Observation Evidence
-- Additive, idempotent migration. Never modifies Migrations 0001-0018.
--
-- Preserves validated public player tags observed in authorized East Coasters
-- community-provider match payloads (and user-supplied exports) as protected,
-- reviewable identity candidates linked to pseudonymous `plr_ecf_<12hex>` IDs.
-- No raw provider JSON payloads are retained; candidates are never promoted to
-- `public.fc27_roster` automatically during ingestion.

CREATE TABLE IF NOT EXISTS public.fc27_player_alias_candidates (
    candidate_id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    player_id                text NOT NULL,
    public_alias             text NOT NULL,
    public_alias_normalized  text NOT NULL,
    alias_hmac_fingerprint   text NOT NULL,
    source_classification    text NOT NULL,
    first_seen_at            timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp(),
    last_seen_at             timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp(),
    observation_count        integer NOT NULL DEFAULT 1,
    distinct_match_count     integer NOT NULL DEFAULT 1,
    verification_status      text NOT NULL DEFAULT 'OBSERVED',
    conflict_status          text NOT NULL DEFAULT 'NONE',
    promoted_at              timestamptz NULL,
    created_at               timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp(),
    updated_at               timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp(),

    CONSTRAINT fc27_player_alias_candidates_player_id_chk
        CHECK (player_id ~ '^plr_ecf_[0-9a-f]{12}$'),
    CONSTRAINT fc27_player_alias_candidates_public_alias_chk
        CHECK (
            pg_catalog.char_length(public_alias) BETWEEN 1 AND 32
            AND public_alias = pg_catalog.btrim(public_alias)
            AND public_alias !~ '[\x00-\x1F\x7F]'
            AND pg_catalog.left(public_alias, 1) NOT IN ('=', '+', '-', '@')
            AND public_alias !~* '(plr_ecf_[0-9a-f]{12}|mref_ecf_[0-9a-f]{12,64}|https?://|www\.|@(everyone|here)|<@[!&]?[0-9]+>|<#[0-9]+>|postgresql://|postgres://|redis://|bearer\s+|password|secret|^\s*unnamed\s+player\s*$)'
        ),
    CONSTRAINT fc27_player_alias_candidates_norm_alias_chk
        CHECK (
            pg_catalog.char_length(public_alias_normalized) BETWEEN 1 AND 32
            AND public_alias_normalized = pg_catalog.btrim(public_alias_normalized)
            AND public_alias_normalized !~ '[A-Z]'
            AND public_alias_normalized !~ '[\x00-\x1F\x7F]'
        ),
    CONSTRAINT fc27_player_alias_candidates_hmac_chk
        CHECK (alias_hmac_fingerprint ~ '^[0-9a-f]{64}$'),
    CONSTRAINT fc27_player_alias_candidates_source_chk
        CHECK (
            source_classification IN (
                'AUTHORIZED_MATCH_PAYLOAD',
                'OPERATOR_CONFIRMED',
                'USER_SUPPLIED_EXPORT'
            )
        ),
    CONSTRAINT fc27_player_alias_candidates_verification_status_chk
        CHECK (
            verification_status IN (
                'OBSERVED',
                'STABLE',
                'CONFLICTED',
                'OPERATOR_VERIFIED',
                'PROMOTED',
                'REJECTED'
            )
        ),
    CONSTRAINT fc27_player_alias_candidates_conflict_status_chk
        CHECK (
            conflict_status IN (
                'NONE',
                'CONFLICTED',
                'SAME_PLAYER_MULTIPLE_ALIASES',
                'CROSS_PLAYER_SAME_ALIAS',
                'BOTH'
            )
        ),
    CONSTRAINT fc27_player_alias_candidates_obs_count_chk
        CHECK (observation_count >= 1),
    CONSTRAINT fc27_player_alias_candidates_distinct_match_count_chk
        CHECK (distinct_match_count >= 1 AND distinct_match_count <= observation_count),
    CONSTRAINT fc27_player_alias_candidates_timestamps_chk
        CHECK (first_seen_at <= last_seen_at AND updated_at >= created_at),
    CONSTRAINT fc27_player_alias_candidates_promoted_at_chk
        CHECK (
            (
                verification_status = 'PROMOTED'
                AND promoted_at IS NOT NULL
                AND promoted_at >= first_seen_at
            )
            OR (
                verification_status <> 'PROMOTED'
                AND promoted_at IS NULL
            )
        ),
    CONSTRAINT fc27_player_alias_candidates_stable_threshold_chk
        CHECK (
            verification_status <> 'STABLE'
            OR (distinct_match_count >= 2 AND conflict_status = 'NONE')
        ),
    CONSTRAINT fc27_player_alias_candidates_player_hmac_source_uk
        UNIQUE (player_id, alias_hmac_fingerprint, source_classification)
);

ALTER TABLE public.fc27_player_alias_candidates OWNER TO fc27_owner;
REVOKE ALL ON public.fc27_player_alias_candidates FROM PUBLIC;

CREATE INDEX IF NOT EXISTS idx_fc27_player_alias_candidates_player_id
    ON public.fc27_player_alias_candidates (player_id);

CREATE INDEX IF NOT EXISTS idx_fc27_player_alias_candidates_hmac
    ON public.fc27_player_alias_candidates (alias_hmac_fingerprint);

CREATE INDEX IF NOT EXISTS idx_fc27_player_alias_candidates_norm_alias
    ON public.fc27_player_alias_candidates (public_alias_normalized);

CREATE INDEX IF NOT EXISTS idx_fc27_player_alias_candidates_verification_status
    ON public.fc27_player_alias_candidates (verification_status);

CREATE INDEX IF NOT EXISTS idx_fc27_player_alias_candidates_conflict_status
    ON public.fc27_player_alias_candidates (conflict_status);

CREATE INDEX IF NOT EXISTS idx_fc27_player_alias_candidates_last_seen
    ON public.fc27_player_alias_candidates (last_seen_at DESC, candidate_id DESC);

CREATE INDEX IF NOT EXISTS idx_fc27_player_alias_candidates_review_lookup
    ON public.fc27_player_alias_candidates (player_id, verification_status, conflict_status, last_seen_at DESC);

CREATE TABLE IF NOT EXISTS public.fc27_player_alias_candidate_observations (
    candidate_id  bigint NOT NULL
        REFERENCES public.fc27_player_alias_candidates (candidate_id) ON DELETE CASCADE,
    match_ref     text NOT NULL,
    observed_at   timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp(),

    CONSTRAINT fc27_player_alias_candidate_observations_pk
        PRIMARY KEY (candidate_id, match_ref),
    CONSTRAINT fc27_player_alias_candidate_observations_match_ref_chk
        CHECK (match_ref ~ '^(mref_ecf_[0-9a-f]{12,64}|[0-9a-f]{64})$')
);

ALTER TABLE public.fc27_player_alias_candidate_observations OWNER TO fc27_owner;
REVOKE ALL ON public.fc27_player_alias_candidate_observations FROM PUBLIC;

CREATE INDEX IF NOT EXISTS idx_fc27_player_alias_candidate_observations_match_ref
    ON public.fc27_player_alias_candidate_observations (match_ref);
