-- =============================================================================
-- Migration 0013: FC 27 Manual Match Results Domain & Audit Foundation
-- =============================================================================
-- Creates a dedicated PostgreSQL 16 domain for operator-entered Discord Match
-- Results while keeping provider/import-derived analytical tables
-- (public.fc27_matches, public.fc27_player_match_stats) completely unchanged.
--
-- Tables created (owned by fc27_owner):
--   1. public.fc27_manual_matches
--   2. public.fc27_manual_match_players
--   3. public.fc27_manual_match_events
--   4. public.fc27_manual_match_audit
--
-- Invariants enforced at database level:
--   - source_classification is strictly constrained to 'MANUAL_MATCH_RESULT'.
--   - Manual player labels are operator-entered display labels only; no Xbox,
--     PSN, EA, Persona, or Nucleus account IDs are stored.
--   - Scores constrained to 0..30; possession and pass_accuracy to 0..100;
--     shots_on_target cannot exceed shots; all counts are nonnegative.
--   - Discord guild, channel, message, and actor IDs are validated snowflakes.
--   - Optimistic concurrency enforced via monotonically increasing revision.
--   - Soft deletion supported via deleted_at / deleted_by / delete_reason.
--   - public.fc27_manual_match_audit is append-only (UPDATE/DELETE rejected).
-- =============================================================================

-- -----------------------------------------------------------------------------
-- 1. public.fc27_manual_matches
-- -----------------------------------------------------------------------------
CREATE TABLE public.fc27_manual_matches (
    match_id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    club_id                 text NOT NULL DEFAULT '330323',
    platform                text NOT NULL DEFAULT 'common-gen5',
    game_version            text NOT NULL DEFAULT 'FC27',
    opponent                text NOT NULL,
    opponent_normalized     text NOT NULL,
    kickoff_at              timestamptz NULL,
    match_date              text NULL,
    match_time              text NULL,
    home_score              integer NULL,
    away_score              integer NULL,
    status                  text NOT NULL,
    motm_display_label      text NULL,
    motm_normalized_label   text NULL,
    possession              integer NULL,
    shots                   integer NULL,
    shots_on_target         integer NULL,
    passes                  integer NULL,
    pass_accuracy           integer NULL,
    corners                 integer NULL,
    tackles                 integer NULL,
    fouls                   integer NULL,
    notes                   text NULL,
    discord_guild_id        text NULL,
    discord_channel_id      text NULL,
    discord_message_id      text NULL,
    source_classification   text NOT NULL DEFAULT 'MANUAL_MATCH_RESULT',
    created_by              text NOT NULL,
    updated_by              text NOT NULL,
    created_at              timestamptz NOT NULL DEFAULT now(),
    updated_at              timestamptz NOT NULL DEFAULT now(),
    revision                integer NOT NULL DEFAULT 1,
    deleted_at              timestamptz NULL,
    deleted_by              text NULL,
    delete_reason           text NULL,

    CONSTRAINT fc27_manual_matches_club_id_chk
        CHECK (length(btrim(club_id)) BETWEEN 1 AND 64),
    CONSTRAINT fc27_manual_matches_platform_chk
        CHECK (length(btrim(platform)) BETWEEN 1 AND 32),
    CONSTRAINT fc27_manual_matches_game_version_chk
        CHECK (game_version = 'FC27'),
    CONSTRAINT fc27_manual_matches_opponent_chk
        CHECK (
            length(btrim(opponent)) BETWEEN 1 AND 80
            AND opponent !~ '[\x00-\x1F\x7F]'
        ),
    CONSTRAINT fc27_manual_matches_opponent_norm_chk
        CHECK (
            length(btrim(opponent_normalized)) BETWEEN 1 AND 80
            AND opponent_normalized = lower(btrim(opponent_normalized))
        ),
    CONSTRAINT fc27_manual_matches_match_date_chk
        CHECK (
            match_date IS NULL
            OR (length(btrim(match_date)) BETWEEN 1 AND 32 AND match_date !~ '[\x00-\x1F\x7F]')
        ),
    CONSTRAINT fc27_manual_matches_match_time_chk
        CHECK (
            match_time IS NULL
            OR (length(btrim(match_time)) BETWEEN 1 AND 32 AND match_time !~ '[\x00-\x1F\x7F]')
        ),
    CONSTRAINT fc27_manual_matches_home_score_chk
        CHECK (home_score IS NULL OR (home_score >= 0 AND home_score <= 30)),
    CONSTRAINT fc27_manual_matches_away_score_chk
        CHECK (away_score IS NULL OR (away_score >= 0 AND away_score <= 30)),
    CONSTRAINT fc27_manual_matches_status_chk
        CHECK (status IN ('SCHEDULED', 'FULL_TIME')),
    CONSTRAINT fc27_manual_matches_status_scores_chk
        CHECK (
            (status = 'SCHEDULED' AND home_score IS NULL AND away_score IS NULL)
            OR (status = 'FULL_TIME' AND home_score IS NOT NULL AND away_score IS NOT NULL)
        ),
    CONSTRAINT fc27_manual_matches_motm_label_chk
        CHECK (
            motm_display_label IS NULL
            OR (length(btrim(motm_display_label)) BETWEEN 1 AND 48 AND motm_display_label !~ '[\x00-\x1F\x7F]')
        ),
    CONSTRAINT fc27_manual_matches_motm_norm_chk
        CHECK (
            (motm_display_label IS NULL AND motm_normalized_label IS NULL)
            OR (
                motm_display_label IS NOT NULL
                AND motm_normalized_label IS NOT NULL
                AND length(btrim(motm_normalized_label)) BETWEEN 1 AND 48
                AND motm_normalized_label = lower(btrim(motm_normalized_label))
            )
        ),
    CONSTRAINT fc27_manual_matches_possession_chk
        CHECK (possession IS NULL OR (possession >= 0 AND possession <= 100)),
    CONSTRAINT fc27_manual_matches_shots_chk
        CHECK (shots IS NULL OR (shots >= 0 AND shots <= 200)),
    CONSTRAINT fc27_manual_matches_shots_on_target_chk
        CHECK (shots_on_target IS NULL OR (shots_on_target >= 0 AND shots_on_target <= 200)),
    CONSTRAINT fc27_manual_matches_shots_target_le_shots_chk
        CHECK (
            shots_on_target IS NULL
            OR (shots IS NOT NULL AND shots_on_target <= shots)
        ),
    CONSTRAINT fc27_manual_matches_passes_chk
        CHECK (passes IS NULL OR (passes >= 0 AND passes <= 2000)),
    CONSTRAINT fc27_manual_matches_pass_accuracy_chk
        CHECK (pass_accuracy IS NULL OR (pass_accuracy >= 0 AND pass_accuracy <= 100)),
    CONSTRAINT fc27_manual_matches_corners_chk
        CHECK (corners IS NULL OR (corners >= 0 AND corners <= 100)),
    CONSTRAINT fc27_manual_matches_tackles_chk
        CHECK (tackles IS NULL OR (tackles >= 0 AND tackles <= 500)),
    CONSTRAINT fc27_manual_matches_fouls_chk
        CHECK (fouls IS NULL OR (fouls >= 0 AND fouls <= 200)),
    CONSTRAINT fc27_manual_matches_notes_chk
        CHECK (
            notes IS NULL
            OR (length(btrim(notes)) BETWEEN 1 AND 280 AND notes !~ '[\x00-\x1F\x7F]')
        ),
    CONSTRAINT fc27_manual_matches_guild_snowflake_chk
        CHECK (discord_guild_id IS NULL OR discord_guild_id ~ '^[0-9]{1,20}$'),
    CONSTRAINT fc27_manual_matches_channel_snowflake_chk
        CHECK (discord_channel_id IS NULL OR discord_channel_id ~ '^[0-9]{1,20}$'),
    CONSTRAINT fc27_manual_matches_message_snowflake_chk
        CHECK (discord_message_id IS NULL OR discord_message_id ~ '^[0-9]{1,20}$'),
    CONSTRAINT fc27_manual_matches_source_classification_chk
        CHECK (source_classification = 'MANUAL_MATCH_RESULT'),
    CONSTRAINT fc27_manual_matches_created_by_chk
        CHECK (created_by ~ '^[0-9]{1,20}$'),
    CONSTRAINT fc27_manual_matches_updated_by_chk
        CHECK (updated_by ~ '^[0-9]{1,20}$'),
    CONSTRAINT fc27_manual_matches_revision_chk
        CHECK (revision >= 1),
    CONSTRAINT fc27_manual_matches_deleted_by_chk
        CHECK (deleted_by IS NULL OR deleted_by ~ '^[0-9]{1,20}$'),
    CONSTRAINT fc27_manual_matches_delete_reason_chk
        CHECK (
            delete_reason IS NULL
            OR (length(btrim(delete_reason)) BETWEEN 1 AND 200 AND delete_reason !~ '[\x00-\x1F\x7F]')
        ),
    CONSTRAINT fc27_manual_matches_soft_delete_consistency_chk
        CHECK (
            (deleted_at IS NULL AND deleted_by IS NULL AND delete_reason IS NULL)
            OR (deleted_at IS NOT NULL AND deleted_by IS NOT NULL)
        )
);

ALTER TABLE public.fc27_manual_matches OWNER TO fc27_owner;

CREATE INDEX idx_fc27_manual_matches_club_active_order
    ON public.fc27_manual_matches (club_id, status, COALESCE(kickoff_at, created_at) DESC, match_id DESC)
    WHERE deleted_at IS NULL;

CREATE INDEX idx_fc27_manual_matches_opponent_lookup
    ON public.fc27_manual_matches (club_id, opponent_normalized, match_id DESC)
    WHERE deleted_at IS NULL;

-- -----------------------------------------------------------------------------
-- 2. public.fc27_manual_match_players
-- -----------------------------------------------------------------------------
CREATE TABLE public.fc27_manual_match_players (
    player_stat_id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id                    bigint NOT NULL,
    normalized_display_label    text NOT NULL,
    safe_display_label          text NOT NULL,
    goals                       integer NOT NULL DEFAULT 0,
    assists                     integer NOT NULL DEFAULT 0,
    tackles                     integer NULL,
    passes                      integer NULL,
    pass_accuracy               integer NULL,
    shots                       integer NULL,
    rating                      numeric(4, 2) NULL,
    source_classification       text NOT NULL DEFAULT 'MANUAL_MATCH_RESULT',
    created_at                  timestamptz NOT NULL DEFAULT now(),
    updated_at                  timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT fc27_manual_match_players_match_fk
        FOREIGN KEY (match_id)
        REFERENCES public.fc27_manual_matches (match_id)
        ON DELETE RESTRICT,
    CONSTRAINT fc27_manual_match_players_match_label_uk
        UNIQUE (match_id, normalized_display_label),
    CONSTRAINT fc27_manual_match_players_norm_label_chk
        CHECK (
            length(btrim(normalized_display_label)) BETWEEN 1 AND 48
            AND normalized_display_label = lower(btrim(normalized_display_label))
            AND normalized_display_label !~ '[\x00-\x1F\x7F]'
        ),
    CONSTRAINT fc27_manual_match_players_safe_label_chk
        CHECK (
            length(btrim(safe_display_label)) BETWEEN 1 AND 48
            AND safe_display_label !~ '[\x00-\x1F\x7F]'
        ),
    CONSTRAINT fc27_manual_match_players_goals_chk
        CHECK (goals >= 0 AND goals <= 30),
    CONSTRAINT fc27_manual_match_players_assists_chk
        CHECK (assists >= 0 AND assists <= 30),
    CONSTRAINT fc27_manual_match_players_tackles_chk
        CHECK (tackles IS NULL OR (tackles >= 0 AND tackles <= 200)),
    CONSTRAINT fc27_manual_match_players_passes_chk
        CHECK (passes IS NULL OR (passes >= 0 AND passes <= 1000)),
    CONSTRAINT fc27_manual_match_players_pass_accuracy_chk
        CHECK (pass_accuracy IS NULL OR (pass_accuracy >= 0 AND pass_accuracy <= 100)),
    CONSTRAINT fc27_manual_match_players_shots_chk
        CHECK (shots IS NULL OR (shots >= 0 AND shots <= 100)),
    CONSTRAINT fc27_manual_match_players_rating_chk
        CHECK (rating IS NULL OR (rating >= 0.00 AND rating <= 10.00)),
    CONSTRAINT fc27_manual_match_players_source_classification_chk
        CHECK (source_classification = 'MANUAL_MATCH_RESULT')
);

ALTER TABLE public.fc27_manual_match_players OWNER TO fc27_owner;

CREATE INDEX idx_fc27_manual_match_players_match_id
    ON public.fc27_manual_match_players (match_id, goals DESC, assists DESC, normalized_display_label ASC);

CREATE INDEX idx_fc27_manual_match_players_label_lookup
    ON public.fc27_manual_match_players (normalized_display_label, match_id DESC);

-- -----------------------------------------------------------------------------
-- 3. public.fc27_manual_match_events
-- -----------------------------------------------------------------------------
CREATE TABLE public.fc27_manual_match_events (
    event_id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id                    bigint NOT NULL,
    event_type                  text NOT NULL DEFAULT 'GOAL',
    normalized_display_label    text NOT NULL,
    safe_display_label          text NOT NULL,
    event_count                 integer NOT NULL DEFAULT 1,
    display_order               integer NOT NULL DEFAULT 0,
    source_classification       text NOT NULL DEFAULT 'MANUAL_MATCH_RESULT',
    created_at                  timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT fc27_manual_match_events_match_fk
        FOREIGN KEY (match_id)
        REFERENCES public.fc27_manual_matches (match_id)
        ON DELETE RESTRICT,
    CONSTRAINT fc27_manual_match_events_match_type_label_uk
        UNIQUE (match_id, event_type, normalized_display_label),
    CONSTRAINT fc27_manual_match_events_type_chk
        CHECK (event_type IN ('GOAL')),
    CONSTRAINT fc27_manual_match_events_norm_label_chk
        CHECK (
            length(btrim(normalized_display_label)) BETWEEN 1 AND 48
            AND normalized_display_label = lower(btrim(normalized_display_label))
            AND normalized_display_label !~ '[\x00-\x1F\x7F]'
        ),
    CONSTRAINT fc27_manual_match_events_safe_label_chk
        CHECK (
            length(btrim(safe_display_label)) BETWEEN 1 AND 48
            AND safe_display_label !~ '[\x00-\x1F\x7F]'
        ),
    CONSTRAINT fc27_manual_match_events_count_chk
        CHECK (event_count >= 1 AND event_count <= 30),
    CONSTRAINT fc27_manual_match_events_order_chk
        CHECK (display_order >= 0 AND display_order <= 100),
    CONSTRAINT fc27_manual_match_events_source_classification_chk
        CHECK (source_classification = 'MANUAL_MATCH_RESULT')
);

ALTER TABLE public.fc27_manual_match_events OWNER TO fc27_owner;

CREATE INDEX idx_fc27_manual_match_events_match_order
    ON public.fc27_manual_match_events (match_id, display_order ASC, normalized_display_label ASC);

-- -----------------------------------------------------------------------------
-- 4. public.fc27_manual_match_audit (Append-Only Audit Trail)
-- -----------------------------------------------------------------------------
CREATE TABLE public.fc27_manual_match_audit (
    audit_id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_id                bigint NULL,
    action                  text NOT NULL,
    actor_discord_user_id   text NOT NULL,
    discord_guild_id        text NULL,
    discord_channel_id      text NULL,
    discord_message_id      text NULL,
    previous_revision       integer NULL,
    new_revision            integer NULL,
    changed_fields          jsonb NOT NULL DEFAULT '[]'::jsonb,
    audit_metadata          jsonb NOT NULL DEFAULT '{}'::jsonb,
    source_classification   text NOT NULL DEFAULT 'MANUAL_MATCH_RESULT',
    recorded_at             timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT fc27_manual_match_audit_match_fk
        FOREIGN KEY (match_id)
        REFERENCES public.fc27_manual_matches (match_id)
        ON DELETE RESTRICT,
    CONSTRAINT fc27_manual_match_audit_action_chk
        CHECK (
            action IN (
                'CREATE_SCHEDULED',
                'RECORD_RESULT',
                'EDIT_RESULT',
                'SOFT_DELETE_MATCH',
                'RELINK_DISCORD_MESSAGE',
                'UNAUTHORIZED_WRITE_DENIED'
            )
        ),
    CONSTRAINT fc27_manual_match_audit_actor_chk
        CHECK (actor_discord_user_id ~ '^[0-9]{1,20}$'),
    CONSTRAINT fc27_manual_match_audit_guild_chk
        CHECK (discord_guild_id IS NULL OR discord_guild_id ~ '^[0-9]{1,20}$'),
    CONSTRAINT fc27_manual_match_audit_channel_chk
        CHECK (discord_channel_id IS NULL OR discord_channel_id ~ '^[0-9]{1,20}$'),
    CONSTRAINT fc27_manual_match_audit_message_chk
        CHECK (discord_message_id IS NULL OR discord_message_id ~ '^[0-9]{1,20}$'),
    CONSTRAINT fc27_manual_match_audit_prev_rev_chk
        CHECK (previous_revision IS NULL OR previous_revision >= 1),
    CONSTRAINT fc27_manual_match_audit_new_rev_chk
        CHECK (new_revision IS NULL OR new_revision >= 1),
    CONSTRAINT fc27_manual_match_audit_changed_fields_chk
        CHECK (jsonb_typeof(changed_fields) = 'array'),
    CONSTRAINT fc27_manual_match_audit_metadata_chk
        CHECK (jsonb_typeof(audit_metadata) = 'object'),
    CONSTRAINT fc27_manual_match_audit_source_classification_chk
        CHECK (source_classification = 'MANUAL_MATCH_RESULT')
);

ALTER TABLE public.fc27_manual_match_audit OWNER TO fc27_owner;

CREATE INDEX idx_fc27_manual_match_audit_match_recorded
    ON public.fc27_manual_match_audit (match_id, recorded_at DESC, audit_id DESC);

CREATE OR REPLACE FUNCTION public.fc27_forbid_manual_match_audit_mutation()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'fc27_manual_match_audit is append-only; % is prohibited', TG_OP
        USING ERRCODE = '42501';
END;
$$;

ALTER FUNCTION public.fc27_forbid_manual_match_audit_mutation() OWNER TO fc27_owner;

CREATE TRIGGER trg_fc27_manual_match_audit_immutable
BEFORE UPDATE OR DELETE ON public.fc27_manual_match_audit
FOR EACH ROW
EXECUTE FUNCTION public.fc27_forbid_manual_match_audit_mutation();
