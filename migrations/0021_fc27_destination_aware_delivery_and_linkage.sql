CREATE OR REPLACE FUNCTION public.fc27_get_deliveries_for_refresh(
    p_match_ref text
)
RETURNS TABLE (
    delivery_id          bigint,
    destination_key      text,
    message_kind         text,
    guild_id             text,
    channel_id           text,
    message_id           text,
    delivery_state       text,
    allow_roster_refresh boolean
)
LANGUAGE sql
SECURITY DEFINER
STABLE
SET search_path = pg_catalog, pg_temp
AS $$
    SELECT
        d.delivery_id,
        d.destination_key,
        d.message_kind,
        d.guild_id,
        d.channel_id,
        d.message_id,
        d.delivery_state,
        COALESCE(dest.allow_roster_refresh, true) AS allow_roster_refresh
    FROM public.fc27_match_discord_deliveries d
    LEFT JOIN public.fc27_discord_destinations dest ON dest.destination_id = d.destination_id
    WHERE d.match_ref = p_match_ref
      AND d.delivery_state IN ('DELIVERED', 'MISSING', 'REVOKED')
    ORDER BY d.delivery_id ASC;
$$;

