-- Seed Legacy Placeholder Destinations and Import Historical Linkage
-- ---------------------------------------------------------------------

INSERT INTO public.fc27_discord_destinations (
    destination_key,
    guild_id,
    channel_id,
    message_kind,
    transport,
    enabled,
    allow_backfill,
    allow_normal_delivery,
    allow_roster_refresh
) VALUES
    ('legacy-formal', '0', '0', 'FORMAL_RESULT', 'DISCORD_BOT', false, false, false, true),
    ('legacy-team-chat', '0', '0', 'TEAM_CHAT_SUMMARY', 'DISCORD_BOT', false, false, false, true)
ON CONFLICT (destination_key) DO NOTHING;

DO $$
DECLARE
    rec RECORD;
    v_dest_formal_id BIGINT;
    v_dest_tc_id BIGINT;
BEGIN
    IF to_regclass('public.fc27_manual_match_audit') IS NOT NULL THEN
        SELECT destination_id INTO v_dest_formal_id
        FROM public.fc27_discord_destinations
        WHERE destination_key = 'legacy-formal';

        SELECT destination_id INTO v_dest_tc_id
        FROM public.fc27_discord_destinations
        WHERE destination_key = 'legacy-team-chat';

        FOR rec IN
            SELECT DISTINCT ON (COALESCE(audit_metadata->>'match_ref', match_id::text))
                COALESCE(audit_metadata->>'match_ref', match_id::text) AS m_ref,
                discord_guild_id,
                audit_metadata->>'results_channel_id' AS res_chan,
                audit_metadata->>'results_message_id' AS res_msg,
                audit_metadata->>'team_chat_channel_id' AS tc_chan,
                audit_metadata->>'team_chat_message_id' AS tc_msg,
                recorded_at
            FROM public.fc27_manual_match_audit
            WHERE action = 'RELINK_DISCORD_MESSAGE'
              AND audit_metadata->>'kind' = 'discord_message_linkage'
              AND COALESCE(audit_metadata->>'match_ref', match_id::text) IS NOT NULL
            ORDER BY COALESCE(audit_metadata->>'match_ref', match_id::text), audit_id DESC
        LOOP
            IF rec.res_msg IS NOT NULL AND rec.res_msg ~ '^[0-9]+$' THEN
                INSERT INTO public.fc27_match_discord_deliveries (
                    match_ref,
                    destination_id,
                    destination_key,
                    message_kind,
                    guild_id,
                    channel_id,
                    message_id,
                    delivery_state,
                    idempotency_key,
                    created_at,
                    attempted_at,
                    delivered_at
                ) VALUES (
                    rec.m_ref,
                    v_dest_formal_id,
                    'legacy-formal',
                    'FORMAL_RESULT',
                    COALESCE(rec.discord_guild_id, '0'),
                    COALESCE(rec.res_chan, '0'),
                    rec.res_msg,
                    'DELIVERED',
                    'legacy-formal:' || rec.m_ref,
                    rec.recorded_at,
                    rec.recorded_at,
                    rec.recorded_at
                ) ON CONFLICT (match_ref, destination_key, message_kind) DO NOTHING;
            END IF;

            IF rec.tc_msg IS NOT NULL AND rec.tc_msg ~ '^[0-9]+$' THEN
                INSERT INTO public.fc27_match_discord_deliveries (
                    match_ref,
                    destination_id,
                    destination_key,
                    message_kind,
                    guild_id,
                    channel_id,
                    message_id,
                    delivery_state,
                    idempotency_key,
                    created_at,
                    attempted_at,
                    delivered_at
                ) VALUES (
                    rec.m_ref,
                    v_dest_tc_id,
                    'legacy-team-chat',
                    'TEAM_CHAT_SUMMARY',
                    COALESCE(rec.discord_guild_id, '0'),
                    COALESCE(rec.tc_chan, '0'),
                    rec.tc_msg,
                    'DELIVERED',
                    'legacy-team-chat:' || rec.m_ref,
                    rec.recorded_at,
                    rec.recorded_at,
                    rec.recorded_at
                ) ON CONFLICT (match_ref, destination_key, message_kind) DO NOTHING;
            END IF;
        END LOOP;
    END IF;
END $$;


