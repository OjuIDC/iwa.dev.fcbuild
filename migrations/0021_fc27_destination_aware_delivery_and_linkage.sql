-- Migration 0021: Destination-Aware Discord Delivery Registry and Per-Destination Linkage
-- Additive, idempotent migration. Contiguous after Migration 0020.
--
-- 1. Adds `public.fc27_discord_destinations` to register authorized symbolic delivery destinations
--    with independent controls for normal ingestion fan-out, historical backfill, and roster refresh.
-- 2. Adds `public.fc27_match_discord_deliveries` to track every distinct message delivery per match,
--    destination, and message kind, guaranteeing that delivery to one destination does not satisfy another.
-- 3. Imports legacy message linkage from `public.fc27_manual_match_audit` into `legacy-formal` and
--    `legacy-team-chat` records while leaving existing audit logs intact.
-- 4. Introduces SECURITY DEFINER stored procedures for least-privilege reservation, success confirmation,
--    failure recording, and roster refresh lookups.

CREATE TABLE IF NOT EXISTS public.fc27_discord_destinations (
    destination_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    destination_key        text NOT NULL,
    guild_id               text NOT NULL,
    channel_id             text NOT NULL,
    message_kind           text NOT NULL,
    transport              text NOT NULL DEFAULT 'DISCORD_BOT',
    enabled                boolean NOT NULL DEFAULT TRUE,
    allow_backfill         boolean NOT NULL DEFAULT TRUE,
    allow_normal_delivery  boolean NOT NULL DEFAULT TRUE,
    allow_roster_refresh   boolean NOT NULL DEFAULT TRUE,
    created_at             timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp(),
    updated_at             timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp(),

    CONSTRAINT fc27_discord_dest_key_chk
        CHECK (destination_key ~ '^[a-z0-9_-]{1,64}$'),
    CONSTRAINT fc27_discord_dest_guild_chk
        CHECK (guild_id ~ '^[0-9]{1,30}$'),
    CONSTRAINT fc27_discord_dest_channel_chk
        CHECK (channel_id ~ '^[0-9]{1,30}$'),
    CONSTRAINT fc27_discord_dest_kind_chk
        CHECK (message_kind IN ('FORMAL_RESULT', 'TEAM_CHAT_SUMMARY')),
    CONSTRAINT fc27_discord_dest_transport_chk
        CHECK (transport IN ('DISCORD_BOT', 'WEBHOOK'))
);

