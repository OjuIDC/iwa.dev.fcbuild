CREATE OR REPLACE FUNCTION public.fc27_reserve_discord_delivery(
    p_match_ref        text,
    p_destination_key  text,
    p_message_kind     text,
    p_source_job_id    bigint,
    p_idempotency_key  text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
    v_dest public.fc27_discord_destinations%ROWTYPE;
    v_existing public.fc27_match_discord_deliveries%ROWTYPE;
    v_delivery_id bigint;
    v_now timestamptz := pg_catalog.clock_timestamp();
BEGIN
    SELECT * INTO v_dest
    FROM public.fc27_discord_destinations
    WHERE destination_key = p_destination_key;

    IF NOT FOUND THEN
        RETURN jsonb_build_object(
            'status', 'ERROR',
            'error', 'DESTINATION_NOT_FOUND',
            'destination_key', p_destination_key
        );
    END IF;

    IF NOT v_dest.enabled THEN
        RETURN jsonb_build_object(
            'status', 'SKIPPED_DISABLED',
            'destination_key', p_destination_key
        );
    END IF;

    IF v_dest.message_kind <> p_message_kind THEN
        RETURN jsonb_build_object(
            'status', 'ERROR',
            'error', 'MESSAGE_KIND_MISMATCH',
            'expected_kind', v_dest.message_kind,
            'requested_kind', p_message_kind
        );
    END IF;

    SELECT * INTO v_existing
    FROM public.fc27_match_discord_deliveries
    WHERE match_ref = p_match_ref
      AND destination_key = p_destination_key
      AND message_kind = p_message_kind
    FOR UPDATE;

    IF FOUND THEN
        IF v_existing.delivery_state = 'DELIVERED' THEN
            RETURN jsonb_build_object(
                'status', 'ALREADY_DELIVERED',
                'delivery_id', v_existing.delivery_id,
                'destination_key', v_dest.destination_key,
                'guild_id', v_existing.guild_id,
                'channel_id', v_existing.channel_id,
                'message_id', v_existing.message_id
            );
        END IF;

        UPDATE public.fc27_match_discord_deliveries
        SET delivery_state = 'CLAIMED',
            attempted_at = v_now,
            source_job_id = COALESCE(p_source_job_id, source_job_id),
            updated_at = v_now
        WHERE delivery_id = v_existing.delivery_id;

        RETURN jsonb_build_object(
            'status', 'CLAIMED',
            'delivery_id', v_existing.delivery_id,
            'destination_key', v_dest.destination_key,
            'guild_id', v_dest.guild_id,
            'channel_id', v_dest.channel_id
        );
    END IF;

    INSERT INTO public.fc27_match_discord_deliveries (
        match_ref,
        destination_id,
        destination_key,
        message_kind,
        guild_id,
        channel_id,
        delivery_state,
        idempotency_key,
        source_job_id,
        attempted_at,
        created_at,
        updated_at
    ) VALUES (
        p_match_ref,
        v_dest.destination_id,
        v_dest.destination_key,
        p_message_kind,
        v_dest.guild_id,
        v_dest.channel_id,
        'CLAIMED',
        p_idempotency_key,
        p_source_job_id,
        v_now,
        v_now,
        v_now
    )
    RETURNING delivery_id INTO v_delivery_id;

    RETURN jsonb_build_object(
        'status', 'CLAIMED',
        'delivery_id', v_delivery_id,
        'destination_key', v_dest.destination_key,
        'guild_id', v_dest.guild_id,
        'channel_id', v_dest.channel_id
    );
END;
$$;

