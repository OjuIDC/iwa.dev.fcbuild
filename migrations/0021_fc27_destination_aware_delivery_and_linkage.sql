CREATE OR REPLACE FUNCTION public.fc27_upsert_discord_destination(
    p_destination_key       text,
    p_guild_id              text,
    p_channel_id            text,
    p_message_kind          text,
    p_allow_backfill        boolean DEFAULT true,
    p_allow_normal_delivery boolean DEFAULT true,
    p_allow_roster_refresh  boolean DEFAULT true
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, pg_temp
AS $$
DECLARE
    v_id bigint;
    v_now timestamptz := pg_catalog.clock_timestamp();
BEGIN
    INSERT INTO public.fc27_discord_destinations (
        destination_key,
        guild_id,
        channel_id,
        message_kind,
        transport,
        enabled,
        allow_backfill,
        allow_normal_delivery,
        allow_roster_refresh,
        created_at,
        updated_at
    ) VALUES (
        p_destination_key,
        p_guild_id,
        p_channel_id,
        p_message_kind,
        'DISCORD_BOT',
        true,
        p_allow_backfill,
        p_allow_normal_delivery,
        p_allow_roster_refresh,
        v_now,
        v_now
    )
    ON CONFLICT (destination_key) DO UPDATE
    SET guild_id = EXCLUDED.guild_id,
        channel_id = EXCLUDED.channel_id,
        message_kind = EXCLUDED.message_kind,
        enabled = true,
        allow_backfill = EXCLUDED.allow_backfill,
        allow_normal_delivery = EXCLUDED.allow_normal_delivery,
        allow_roster_refresh = EXCLUDED.allow_roster_refresh,
        updated_at = v_now
    RETURNING destination_id INTO v_id;

    RETURN v_id;
END;
$$;

