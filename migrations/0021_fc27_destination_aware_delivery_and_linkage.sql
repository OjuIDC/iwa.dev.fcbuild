CREATE TABLE IF NOT EXISTS public.fc27_match_discord_deliveries (
    delivery_id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    match_ref              text NOT NULL,
    destination_id         bigint NOT NULL
        REFERENCES public.fc27_discord_destinations (destination_id) ON DELETE RESTRICT,
    destination_key        text NOT NULL,
    message_kind           text NOT NULL,
    guild_id               text NOT NULL,
    channel_id             text NOT NULL,
    message_id             text NULL,
    delivery_state         text NOT NULL DEFAULT 'PENDING',
    idempotency_key        text NOT NULL,
    source_job_id          bigint NULL,
    created_at             timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp(),
    attempted_at           timestamptz NULL,
    delivered_at           timestamptz NULL,
    updated_at             timestamptz NOT NULL DEFAULT pg_catalog.clock_timestamp(),
    last_error_category    text NULL,

    CONSTRAINT fc27_deliveries_match_ref_chk
        CHECK (
            pg_catalog.char_length(match_ref) BETWEEN 1 AND 128
            AND match_ref = pg_catalog.btrim(match_ref)
        ),
    CONSTRAINT fc27_deliveries_dest_key_chk
        CHECK (destination_key ~ '^[a-z0-9_-]{1,64}$'),
    CONSTRAINT fc27_deliveries_kind_chk
        CHECK (message_kind IN ('FORMAL_RESULT', 'TEAM_CHAT_SUMMARY')),
    CONSTRAINT fc27_deliveries_guild_chk
        CHECK (guild_id ~ '^[0-9]{1,30}$'),
    CONSTRAINT fc27_deliveries_channel_chk
        CHECK (channel_id ~ '^[0-9]{1,30}$'),
    CONSTRAINT fc27_deliveries_message_chk
        CHECK (message_id IS NULL OR message_id ~ '^[0-9]{1,30}$'),
    CONSTRAINT fc27_deliveries_state_chk
        CHECK (delivery_state IN ('PENDING', 'CLAIMED', 'DELIVERED', 'FAILED', 'REVOKED', 'MISSING')),
    CONSTRAINT fc27_deliveries_error_cat_chk
        CHECK (last_error_category IS NULL OR last_error_category ~ '^[A-Z0-9_]{1,64}$')
);

